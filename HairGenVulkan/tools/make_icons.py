#!/usr/bin/env python3
"""Regenerate the panel's icon font and its C++ header.

The UI is drawn with Dear ImGui into a CPU framebuffer, so the icons have to be
a real font the atlas can rasterise - not an SVG sprite.  We ship a *subset* of
Material Design Icons (@mdi/font) instead of the full 1.3 MB face: only the
glyphs the panel references are extracted (fontTools' subtree subroutiner), which
brings the file down to ~10 kB.

The glyphs stay on their upstream codepoints (U+0F0000..), which is why the
renderer sets IMGUI_USE_WCHAR32 (see third_party/imgui/imconfig.h): with a
16-bit ImWchar those glyphs would not be addressable at all.

Usage (needs `pip install fonttools` and a copy of the @mdi/font package):

    npm pack @mdi/font          # -> font-7.4.47.tgz
    tar xzf font-7.4.47.tgz     # -> package/{css,fonts,scss}
    python3 tools/make_icons.py --mdi package \\
        --ttf assets/fonts/MaterialDesignIcons-Subset.ttf \\
        --header src/ui_icons.hpp
"""
import argparse
import os
import re
import subprocess
import sys

# Every glyph the panel uses.  Adding an icon here is the only step needed; the
# subset and the header are both derived from this list.
ICONS = """
palette brush content-cut tune white-balance-sunny weather-rainy camera face-man
face-woman eye texture-box grid layers-triple opacity water waves weather-windy
chevron-down chevron-right cog refresh content-save image-outline check plus minus
close play pause filmstrip auto-fix lightbulb-on dots-horizontal drag
view-dashboard arrow-left arrow-right information-outline chart-line
scissors-cutting format-color-fill hair-dryer face-man-profile
face-woman-profile account-group shape-outline blur grain water-percent
format-paint dock-window window-maximize window-restore lock target
star-four-points flashlight image-filter-center-focus grid-large checkerboard
adjust brightness-6 sun-thermometer weather-partly-cloudy umbrella percent
cube-outline arrow-expand monitor-screenshot circle-slice-8 gradient-vertical
format-line-style invert-colors
""".split()


def codepoint_range(cps):
    """Collapse a sorted codepoint list into (lo, hi) pairs for ImGui."""
    pairs = []
    for cp in cps:
        if pairs and cp == pairs[-1][1] + 1:
            pairs[-1] = (pairs[-1][0], cp)
        else:
            pairs.append((cp, cp))
    return pairs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mdi", required=True, help="extracted @mdi/font package dir")
    ap.add_argument("--ttf", required=True, help="output subset TTF")
    ap.add_argument("--header", required=True, help="output C++ header")
    ap.add_argument("--version", default="7.4.47")
    args = ap.parse_args()

    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        print("fontTools is required (pip install fonttools)", file=sys.stderr)
        return 1

    css_path = os.path.join(args.mdi, "css", "materialdesignicons.css")
    css = open(css_path, encoding="utf-8").read()
    table = dict(
        re.findall(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)";', css)
    )
    missing = [n for n in ICONS if n not in table]
    if missing:
        print("unknown icon names: " + ", ".join(missing), file=sys.stderr)
        return 1

    names = sorted(set(ICONS))
    src_ttf = os.path.join(args.mdi, "fonts", "materialdesignicons-webfont.ttf")
    cps = [int(table[n], 16) for n in names]

    tmp = args.ttf + ".tmp"
    subprocess.run(
        [
            sys.executable, "-m", "fontTools.subset", src_ttf,
            "--unicodes=" + ",".join("U+%04X" % cp for cp in cps),
            "--output-file=" + tmp,
            "--no-hinting", "--desubroutinize", "--drop-tables+=DSIG",
            "--name-IDs=*", "--recalc-bounds",
        ],
        check=True,
    )
    font = TTFont(tmp)
    kept = set(font.getBestCmap())
    lost = [n for n, cp in zip(names, cps) if cp not in kept]
    if lost:
        print("subsetting dropped: " + ", ".join(lost), file=sys.stderr)
        return 1
    os.replace(tmp, args.ttf)

    ranges = codepoint_range(sorted(set(cps)))
    lines = [
        "// ui_icons.hpp - Material Design Icons subset, generated by tools/make_icons.py.",
        "//",
        "// Source: @mdi/font %s.  Only the glyphs the panel uses are in the shipped" % args.version,
        "// TTF (assets/fonts/MaterialDesignIcons-Subset.ttf).  The codepoints live above",
        "// the BMP, so the build defines IMGUI_USE_WCHAR32.  Do not edit by hand:",
        "// rerun the generator after changing the icon list.",
        "#pragma once",
        "",
        "// clang-format off",
    ]
    for name, cp in zip(names, cps):
        lines.append('#define ICON_%s "\\U%08X"' % (name.upper().replace("-", "_"), cp))
    lines.append("// clang-format on")
    lines += [
        "",
        "namespace hgen {",
        "// Codepoint ranges the icon font covers, as ImGui glyph-range pairs.",
        "static const unsigned int kIconRanges[] = {",
        "    " + ", ".join("0x%05X, 0x%05X" % r for r in ranges),
        "};",
        "constexpr int kIconRangeCount = %d;" % len(ranges),
        "}  // namespace hgen",
        "",
    ]
    with open(args.header, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print("wrote %s (%d glyphs, %d ranges, %d bytes)" % (
        args.header, len(names), len(ranges), os.path.getsize(args.ttf)))
    print("wrote %s" % args.ttf)
    return 0


if __name__ == "__main__":
    sys.exit(main())
