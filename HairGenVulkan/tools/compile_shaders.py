#!/usr/bin/env python3
"""Compile every GLSL shader in shaders/ to SPIR-V and emit src/shaders_generated.hpp.

  python3 tools/compile_shaders.py [--glslang PATH] [--check]

`--check` only validates (does not touch the generated header).
The generated header is checked in so the C++ build needs no shader toolchain.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADERS = os.path.join(ROOT, 'shaders')
OUT_HPP = os.path.join(ROOT, 'src', 'shaders_generated.hpp')


def find_glslang(explicit):
    for c in [explicit, os.environ.get('GLSLANG'), os.path.join(ROOT, 'tools', 'bin', 'glslangValidator'),
              'glslangValidator', 'glslang']:
        if not c:
            continue
        try:
            subprocess.run([c, '--version'], capture_output=True, check=True)
            return c
        except Exception:
            continue
    sys.exit('glslangValidator not found (set GLSLANG=/path/to/glslangValidator)')


INCLUDE_RE = re.compile(r'^\s*#include\s+"([^"]+)"\s*$', re.M)


def preprocess(path, seen=None, depth=0):
    """Expand #include "..." relative to shaders/ (recursively)."""
    seen = seen or set()
    if depth > 16:
        sys.exit('include depth exceeded at ' + path)
    src = open(path).read()
    out = []
    for line in src.splitlines(keepends=True):
        m = INCLUDE_RE.match(line)
        if m:
            inc = os.path.join(SHADERS, m.group(1))
            if inc in seen:
                continue
            seen.add(inc)
            out.append(preprocess(inc, seen, depth + 1))
        else:
            out.append(line)
    return ''.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--glslang', default=None)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    glslang = find_glslang(args.glslang)

    entries = []
    for name in sorted(os.listdir(SHADERS)):
        if not name.endswith(('.vert', '.frag')):
            continue
        src = preprocess(os.path.join(SHADERS, name))
        stage = '.vert' if name.endswith('.vert') else '.frag'
        tmp_src = os.path.join(SHADERS, 'spv', '_' + name)
        os.makedirs(os.path.join(SHADERS, 'spv'), exist_ok=True)
        with open(tmp_src, 'w') as f:
            f.write(src)
        spv = tmp_src + '.spv'
        cmd = [glslang, '-V', '--target-env', 'vulkan1.0', '-S', stage[1:], tmp_src, '-o', spv]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stdout)
            print(r.stderr)
            sys.exit('shader compilation failed: ' + name)
        data = open(spv, 'rb').read()
        entries.append((name, data))
        os.remove(tmp_src)
        os.remove(spv)
        print('  %-22s %6d bytes SPIR-V' % (name, len(data)))

    if args.check:
        print('all %d shaders compiled' % len(entries))
        return

    with open(OUT_HPP, 'w') as f:
        f.write('// Generated by tools/compile_shaders.py - do not edit.\n')
        f.write('#pragma once\n#include <cstddef>\n\n')
        f.write('namespace hgen {\n\n')

        for name, data in entries:
            ident = 'kSpv_' + re.sub(r'[^0-9a-zA-Z]', '_', name)
            f.write('alignas(4) static const unsigned char %s[] = {\n' % ident)
            for i in range(0, len(data), 16):
                f.write('  ' + ','.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
            f.write('};\n\n')
        f.write('static const EmbeddedShader kEmbeddedShaders[] = {\n')
        for name, data in entries:
            ident = 'kSpv_' + re.sub(r'[^0-9a-zA-Z]', '_', name)
            f.write('  {"%s", %s, sizeof(%s)},\n' % (name, ident, ident))
        f.write('};\n\n}  // namespace hgen\n')
    print('wrote %s (%d shaders)' % (OUT_HPP, len(entries)))


if __name__ == '__main__':
    main()
